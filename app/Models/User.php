<?php

namespace App\Models;

use Illuminate\Contracts\Auth\MustVerifyEmail;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Laravel\Sanctum\HasApiTokens;

class User extends Authenticatable
{
    use HasApiTokens, HasFactory, Notifiable;

    /**
     * The attributes that are mass assignable.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'role',
        'phone',
        'is_active',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var array<int, string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * The attributes that should be cast.
     *
     * @var array<string, string>
     */
    protected $casts = [
        'email_verified_at' => 'datetime',
        'is_active' => 'boolean',
    ];

    /**
     * Shipments created/owned by this user.
     */
    public function shipments()
    {
        return $this->hasMany(Shipment::class, 'user_id');
    }

    /**
     * Tracking events recorded/created by this user.
     */
    public function trackingEvents()
    {
        return $this->hasMany(TrackingEvent::class, 'created_by');
    }

    /**
     * Exceptions reported by this user.
     */
    public function reportedExceptions()
    {
        return $this->hasMany(ShipmentException::class, 'reported_by');
    }

    /**
     * Exceptions resolved by this user.
     */
    public function resolvedExceptions()
    {
        return $this->hasMany(ShipmentException::class, 'resolved_by');
    }

    /**
     * Audit logs generated by this user.
     */
    public function auditLogs()
    {
        return $this->hasMany(AuditLog::class, 'user_id');
    }
}
